#!/usr/bin/env python3
"""Regenerate test/stubs/font_metrics.h: per-glyph Roboto metrics for the desktop layout test.

Run after changing a font size in muni_display.yaml. It reads the Roboto files that ESPHome
downloads into .esphome/font/ on the first build, so build once before running this.

    python3 tools/gen_font_metrics.py
"""
import glob, os, sys
import yaml
from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

class Loader(yaml.SafeLoader):
    pass
Loader.add_constructor("!secret", lambda loader, node: "")

cfg = yaml.load(open(os.path.join(ROOT, "muni_display.yaml")), Loader=Loader)
sizes = sorted({(f["file"]["weight"], f["size"]) for f in cfg["font"]})

def ttf(weight):
    hits = glob.glob(os.path.join(ROOT, ".esphome", "font", f"Roboto@{weight}@*.ttf"))
    if not hits:
        sys.exit(f"Roboto weight {weight} not found in .esphome/font/ - build the firmware once first.")
    return hits[0]

chars = [chr(c) for c in range(32, 127)] + ["·"]
out = ["// Generated by tools/gen_font_metrics.py from the Roboto files ESPHome downloads:",
       "// per-glyph advance and ink box (relative to the pen on the baseline, y down).",
       "#pragma once",
       "struct GlyphM { int cp; float adv; int x0, y0, x1, y1; };",
       "struct FontM { int weight, size, ascent, descent; const GlyphM *g; int n; };"]
names = []
for w, s in sizes:
    f = ImageFont.truetype(ttf(w), s)
    asc, desc = f.getmetrics()
    rows = []
    for ch in chars:
        b = f.getbbox(ch, anchor="ls")
        rows.append(f"{{{ord(ch)},{f.getlength(ch):.2f}f,{b[0]},{b[1]},{b[2]},{b[3]}}}")
    nm = f"G_{w}_{s}"
    names.append((w, s, asc, desc, nm))
    out.append(f"static const GlyphM {nm}[] = {{{','.join(rows)}}};")
out.append("static const FontM ALL_FONTS[] = {" +
           ",".join(f"{{{w},{s},{a},{d},{nm},{len(chars)}}}" for w, s, a, d, nm in names) + "};")
path = os.path.join(ROOT, "test", "stubs", "font_metrics.h")
open(path, "w").write("\n".join(out) + "\n")
print(f"wrote {path}: {len(names)} font sizes")
