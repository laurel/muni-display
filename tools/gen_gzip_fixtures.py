#!/usr/bin/env python3
"""Regenerate test/gzip_fixtures.h: gzip test cases for muni.h's decompressor.

    python3 tools/gen_gzip_fixtures.py
"""
import gzip, io, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# A real 511 StopMonitoring response for stop 15644 (with its byte-order mark).
real = open(os.path.join(ROOT, "test", "sample_response.json"), "rb").read()

random.seed(7)
cases = [(f"real response, level {lvl}", real, gzip.compress(real, compresslevel=lvl, mtime=0)) for lvl in (0, 1, 6, 9)]
buf = io.BytesIO()
with gzip.GzipFile(filename="stop.json", mode="wb", fileobj=buf, mtime=0) as f:
    f.write(real)
cases.append(("real response with file name header", real, buf.getvalue()))
big = real * 40
cases.append((f"{len(big) // 1000} KB repetitive (long back-references)", big, gzip.compress(big, 9, mtime=0)))
rnd = bytes(random.getrandbits(8) for _ in range(70000))
cases.append(("70 KB random (stored blocks)", rnd, gzip.compress(rnd, 6, mtime=0)))
mixed = b"".join(bytes(random.getrandbits(8) for _ in range(300)) + b"ABCD" * random.randint(1, 200)
                 for _ in range(200))
cases.append((f"{len(mixed) // 1000} KB mixed random and repeats", mixed, gzip.compress(mixed, 6, mtime=0)))
cases.append(("empty", b"", gzip.compress(b"", mtime=0)))

def arr(bs):
    return "{" + ",".join(str(x) for x in bs) + "}"

lines = ["// Generated by tools/gen_gzip_fixtures.py for test_muni.cpp.", "#pragma once",
         "#include <string>", "#include <vector>",
         "struct GzCase { const char *name; std::string plain, gz; };",
         "static std::vector<GzCase> gz_cases() {", "  std::vector<GzCase> v;"]
for name, plain, gz in cases:
    lines.append(f"  {{ static const unsigned char p[] = {arr(plain) if plain else '{0}'};"
                 f" static const unsigned char g[] = {arr(gz)};")
    lines.append(f"    v.push_back({{\"{name}\", std::string((const char*)p, {len(plain)}),"
                 f" std::string((const char*)g, {len(gz)})}}); }}")
lines += ["  return v;", "}"]
path = os.path.join(ROOT, "test", "gzip_fixtures.h")
open(path, "w").write("\n".join(lines) + "\n")
print(f"wrote {path}: {len(cases)} cases")
